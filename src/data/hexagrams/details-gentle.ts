/** Hậu thiên bát quái: hướng; Tiên thiên bát quái: số. */
const TRIGRAM_LUCK: Record<string, { direction: string; number: number }> = {
  Càn: { direction: "Tây Bắc", number: 1 },
  Đoài: { direction: "Tây", number: 2 },
  Ly: { direction: "Nam", number: 3 },
  Chấn: { direction: "Đông", number: 4 },
  Tốn: { direction: "Đông Nam", number: 5 },
  Khảm: { direction: "Bắc", number: 6 },
  Cấn: { direction: "Đông Bắc", number: 7 },
  Khôn: { direction: "Tây Nam", number: 8 },
};

export function getLuckyHints(
  upper: { name: string; element: string },
  lower: { name: string },
) {
  const a = TRIGRAM_LUCK[upper.name];
  const b = TRIGRAM_LUCK[lower.name];
  return {
    color: ELEMENT_COLORS[upper.element],
    direction: a.direction,
    numbers: a.number === b.number ? `${a.number}` : `${a.number} và ${b.number}`,
  };
}
